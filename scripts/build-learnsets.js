// scripts/build-learnsets.js
// Generates src/engine/data/learnsets-lite.js — a compact per-species list of
// every Gen 9-legal move the species can know (display names), used by the
// engine to reason about the opponent's *unrevealed* moves.
//
// Source: the same compiled learnsets file the Showdown client would load
// (exports.BattleLearnsets = { species: { learnset: { moveid: [sources...] } } }).
// A move is Gen 9-legal if any source tag starts with '9' (9L level-up, 9M
// TM, 9E egg, 9T tutor, 9S special/event). Moves with no entry in
// @smogon/calc's Gen 9 MOVES table can't be damage-calculated, so they're
// dropped.
//
// The output is committed so builds/tests work offline; regenerate it with:
//   npm run learnsets

import { writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { MOVES } from '@smogon/calc';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'engine', 'data', 'learnsets-lite.js');
const SOURCE_URL = 'https://play.pokemonshowdown.com/data/learnsets.js';

const toID = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '');

async function fetchSource() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`learnsets fetch failed: HTTP ${res.status}`);
  return res.text();
}

function parseSource(code) {
  // The file is CommonJS: `exports.BattleLearnsets = {...}`. Evaluate it in a
  // bare sandbox and grab the object.
  const sandbox = { exports: {} };
  runInNewContext(code, sandbox, { filename: 'learnsets.js' });
  return sandbox.exports.BattleLearnsets;
}

const moves9 = MOVES['9'] ?? MOVES[9];
const idToName = {};
for (const name of Object.keys(moves9)) {
  const id = toID(name);
  if (!(id in idToName)) idToName[id] = name;
}

const raw = await fetchSource();
const learnsets = await parseSource(raw);

const out = {};
let gen9Species = 0;
let totalMoves = 0;
for (const [speciesId, entry] of Object.entries(learnsets)) {
  const learnset = entry?.learnset ?? {};
  const names = [];
  for (const [moveId, sources] of Object.entries(learnset)) {
    if (!Array.isArray(sources) || !sources.some((s) => /^9/.test(String(s)))) continue;
    const name = idToName[moveId];
    if (!name) continue;
    if (!names.includes(name)) names.push(name);
  }
  if (!names.length) continue;
  names.sort();
  out[speciesId] = names.join(',');
  gen9Species += 1;
  totalMoves += names.length;
}

const header = [
  '// GENERATED by scripts/build-learnsets.js — do not edit by hand.',
  '// Every Gen 9-legal move each species can know (display names, comma-joined',
  '// move ids), extracted from the Showdown learnsets data. Used by the engine',
  '// to consider moves the opponent has not yet revealed.',
  '// Regenerate: npm run learnsets',
  '',
].join('\n');

const body = `export default Object.freeze(${JSON.stringify(out)});\n`;
writeFileSync(OUT, header + body);

const bytes = Buffer.byteLength(body);
console.log(`wrote ${OUT}`);
console.log(`species: ${gen9Species} | moves: ${totalMoves} | ${(bytes / 1024 / 1024).toFixed(2)} MB`);
console.log(`sample: ${JSON.stringify(Object.entries(out).slice(0, 2))}`);
