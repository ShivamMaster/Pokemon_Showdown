// scripts/build-randoms-data.js
// Builds src/engine/data/randoms-lite.js from pokemon-showdown's official Gen 9
// Random Battle data (data/random-battles/gen9/sets.json). Each species entry
// becomes a compact pipe-separated string:
//
//   "level|move1,move2,...|ability1,ability2|tera1,tera2"
//
// (empty abilities/teras are kept as empty strings so the split is stable)
//
// Run: node scripts/build-randoms-data.js
// The output is committed so the extension never fetches at runtime.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE_URL =
  'https://raw.githubusercontent.com/smogon/pokemon-showdown/master/data/random-battles/gen9/sets.json';
const OUT = path.join(__dirname, '..', 'src', 'engine', 'data', 'randoms-lite.js');

const toID = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '');

async function main() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`fetch failed: HTTP ${res.status}`);
  const data = await res.json();

  const out = {};
  let withSets = 0;
  for (const [species, entry] of Object.entries(data)) {
    const level = entry?.level ?? 100;
    const sets = entry?.sets ?? [];
    // The moves a random team can roll for this species: the union of every
    // template role's movepool (a template picks a random subset of its pool).
    const moves = [...new Set(sets.flatMap((s) => s.movepool ?? []))];
    const abilities = [...new Set(sets.flatMap((s) => s.abilities ?? []))];
    const teras = [...new Set(sets.flatMap((s) => s.teraTypes ?? []))];
    if (!moves.length) continue; // not a random-battle species
    withSets += 1;
    out[toID(species)] = `${level}|${moves.join(',')}|${abilities.join(',')}|${teras.join(',')}`;
  }

  const body =
    '// src/engine/data/randoms-lite.js\n' +
    '// Generated by scripts/build-randoms-data.js from pokemon-showdown\'s Gen 9\n' +
    '// Random Battle data (data/random-battles/gen9/sets.json). Compact form:\n' +
    '//   "level|move1,move2|ability1,ability2|tera1,tera2"\n' +
    `// ${Object.keys(out).length} species (fetched from ${SOURCE_URL}).\n` +
    'export default Object.freeze(' +
    JSON.stringify(out) +
    ');\n';

  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}: ${Object.keys(out).length} species (${body.length} bytes)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
